import assert from 'node:assert/strict';
import {chromium} from 'playwright';
import {mkdir} from 'node:fs/promises';
await mkdir('.test-artifacts/unified',{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true});
try{
 const p=await browser.newPage({viewport:{width:1440,height:900}}),errors=[],requests=[];
 p.on('pageerror',e=>errors.push(e.message));p.on('request',r=>requests.push(r.url()));
 await p.addInitScript(()=>{localStorage.setItem('circuit-lab.story.progress.v1',JSON.stringify({active:9,completed:[2,7]}));localStorage.setItem('circuit-lab.game.progress.v1',JSON.stringify({active:8,completed:[1,2]}));});
 await p.goto('http://localhost:4173/#city');await p.locator('.story-world canvas').waitFor();
 assert.equal(await p.locator('.mode-switch button').count(),2);
 assert.deepEqual(await p.locator('.mode-switch button').allTextContents(),['آزمایشگاه','شهر روشن']);
 assert.equal(new URL(p.url()).hash,'#game');
 assert.equal(await p.locator('.story-heading h1').innerText(),'دروازهٔ محله');
 assert.equal(requests.some(url=>url.includes('/CampaignHost.js')),false,'Old story stages are not the public game');
 assert.equal(requests.some(url=>url.includes('/ray-city/CityRayHost.js')),true);
 assert.equal(await p.locator('[data-story-object="city-device:guard-lamp"]').count(),1);
 await p.screenshot({path:'.test-artifacts/unified/desktop.png'});
 await p.locator('[data-story-action="begin"]').click();
 await p.locator('[data-story-action="levels"]').first().click();assert.match(await p.locator('.story-dialog').innerText(),/درمانگاه محله/);
 await p.locator('[data-story-action="mission:3"]').click();await p.locator('.ray-city-stage').waitFor();
 await p.locator('[data-mode="lab"]').click();assert.ok(await p.locator('.main-grid').isVisible());
 await p.locator('[data-mode="story"]').click();assert.ok(await p.locator('.ray-city-stage').isVisible());
 await p.evaluate(()=>location.hash='#workshop');await p.waitForURL('**/#game');
 await p.reload();await p.locator('.ray-city-stage').waitFor();
 assert.match(await p.locator('.story-heading h1').innerText(),/درمانگاه/,'City mission resumes independently of prior story progress');
 await p.setViewportSize({width:390,height:844});
 assert.equal(await p.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 assert.equal(await p.locator('.mode-switch button').count(),2);
 await p.screenshot({path:'.test-artifacts/unified/mobile.png'});
 assert.deepEqual(errors,[]);console.log('PASS unified modes: two entries, old links redirected, original city missions, physical devices, independent progress, stage resume and mobile.');
}finally{await browser.close();}
