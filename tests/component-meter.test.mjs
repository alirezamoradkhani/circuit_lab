import assert from 'node:assert/strict';
import {AdventureSession} from '../src/city/AdventureSession.js';
import {measurePart} from '../src/city/ComponentMeter.js';
const s=new AdventureSession(2);
assert.equal(measurePart(s,'p1').voltage,12);
assert.equal(measurePart(s,'p2').voltage,0);
assert.equal(measurePart(s,'p4').voltage,12);
assert.equal(measurePart(s,'p4').current,0);
assert.equal(measurePart(s,'p5').voltage,6);
assert.equal(measurePart(s,'p5').current,.5);
s.toggleSwitch();assert.equal(measurePart(s,'p2').voltage,12);assert.equal(measurePart(s,'p3').current,0);
s.toggleSwitch();s.tripped=true;assert.equal(measurePart(s,'p3').current,0);assert.equal(measurePart(s,'p1').voltage,12);
s.tripped=false;s.board.wires=s.board.wires.filter(w=>!w.some(t=>t.startsWith('p3:')));
assert.equal(measurePart(s,'p3').voltage,null);assert.ok(measurePart(s,'p3').error);
const shop=new AdventureSession(1),before=shop.board.snapshot();
assert.ok(Math.abs(measurePart(shop,'p3').voltage-2.4)<1e-8);
assert.ok(Math.abs(measurePart(shop,'p4').current-.8)<1e-8);
assert.equal(shop.board.snapshot(),before,'measurement never edits components');
shop.board.connect('p1:0','p2:1');shop.board.connect('p2:1','p1:1');
assert.equal(measurePart(shop,'p1').voltage,null);assert.ok(measurePart(shop,'p1').error);
assert.equal(measurePart(shop,'missing'),null);
console.log('PASS: direct component voltage/current, failed lamp, open switch, tripped protector, floating nodes and short circuit.');
