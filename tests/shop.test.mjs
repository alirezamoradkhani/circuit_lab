import assert from 'node:assert/strict';
import {AdventureSession} from '../src/city/AdventureSession.js';
const near=(a,b)=>assert.ok(Math.abs(a-b)<1e-8,`${a} ≈ ${b}`);
const s=new AdventureSession(1),repair=s.shop;
repair.placeProbe('red','p1:0');assert.equal(repair.voltage,null);
repair.placeProbe('black','p1:1');near(repair.voltage,12);
repair.placeProbe('red','p3:0');repair.placeProbe('black','p3:1');near(repair.voltage,2.4);
repair.placeProbe('red','p4:0');repair.placeProbe('black','p4:1');near(repair.voltage,9.6);
repair.placeProbe('red','p1:1');repair.placeProbe('black','p1:0');near(repair.voltage,-12);
repair.placeProbe('red','p1:0');near(repair.voltage,0);
repair.placeProbe('red','invalid');assert.equal(repair.probes.red,'p1:0');
repair.remove();assert.equal(repair.empty,false,'powered socket cannot be removed');
s.install(24);assert.equal(s.credits,60,'occupied socket cannot be overwritten');
assert.equal(s.test(),false);assert.equal(s.tripped,true);assert.equal(repair.brightness,0);
repair.placeProbe('red','p4:0');repair.placeProbe('black','p4:1');near(repair.voltage,0);
s.toggleSwitch();repair.remove();assert.equal(repair.empty,true);near(s.current,0);
s.resetFuse();assert.equal(s.test(),false,'empty socket cannot complete a mission');
s.install(36);assert.equal(repair.empty,false);assert.equal(s.credits,30);
s.toggleSwitch();assert.equal(s.test(),false);near(repair.brightness,.5625);
s.toggleSwitch();assert.equal(repair.brightness,0);repair.remove();s.install(24);s.toggleSwitch();
repair.placeProbe('red','p4:0');repair.placeProbe('black','p4:1');near(repair.voltage,4);
assert.equal(s.test(),true);assert.equal(repair.brightness,1);assert.equal(s.spent,55);
repair.remove();assert.equal(repair.empty,false,'won circuit is immutable');
console.log('PASS: signed two-probe measurements, open sockets, protector state, physical replacement, credit accounting and brightness.');
