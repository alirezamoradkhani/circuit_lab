export function seedMission(board, mission) {
  const battery=board.add('battery',220,240);
  const sw=board.add('switch',520,240); sw.closed=true;
  const loads=[];
  for(const type of ['resistor','lamp']) for(let n=0;n<(mission.parts[type]||0);n++) {
    loads.push(board.add(type,260+loads.length*280,540));
  }
  if(mission.id==='shop'||mission.id==='station') loads[0].value=3;
  const path=[battery,sw,...loads];
  board.connect(battery.id+':0',sw.id+':0');
  for(let n=1;n<path.length-1;n++) board.connect(path[n].id+':1',path[n+1].id+':0');
  if(mission.id!=='gate') board.connect(loads.at(-1).id+':1',battery.id+':1');
  // Deliberately faulty legacy wiring; the editor prevents creating this bypass.
  if(mission.id==='station') board.wires.push([sw.id+':0',sw.id+':1']);
}
