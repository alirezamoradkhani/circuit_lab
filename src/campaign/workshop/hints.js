import {powered,totalBatteryLoad} from './electricity.js';
import {NAMES} from './layout.js';

const hint=(key,title,reason,clue,steps)=>({key,title,reason,clue,steps});
const unplug='ابزار کابل را انتخاب کن، روی باتری رِی بزن و «جدا کردن کابل» را بزن.';
const charge='با ابزار دست روی پریز پشت چرخ‌دستی بزن تا رِی کنارش برود؛ بعد با ابزار کابل، پریز و باتری رِی را انتخاب کن.';

// Pure diagnosis: opening help must never move Ray or change the circuit.
export function workshopHint(s){
  if(s.completed)return hint('complete','از تعمیرگاه بیرون آمدی',
    'رسید همراه توست و مسیر کوچه باز شده است.',
    'این مرحله تمام شده؛ رد پاک‌رو در ادامهٔ داستان دنبال می‌شود.',
    ['فعلاً فقط فصل اول قابل بازی است. برای امتحان مسیر دیگر، از «شروع تازه» استفاده کن.']);
  if(!s.started)return hint('begin','باتری گم شده؛ راه خروج را پیدا کن',
    'پاک‌رو باتری یدکی را برده و کرکرهٔ تعمیرگاه بسته است.',
    'رِی هنوز بیدار نشده. ماجرا را شروع کن و اطراف تعمیرگاه را ببین.',
    ['راهنما را ببند و «بیدار شو» را بزن. پس از مقدمه، چرخ‌دستی وسط راه را بررسی کن.']);
  if(s.pushing)return hint('pushing','رِی دارد راه را باز می‌کند',
    'چرخ‌دستی هنوز روی ریل حرکت می‌کند؛ این کار انرژی باتری نمی‌خواهد.',
    'راهنما را ببند و بگذار حرکت چرخ‌دستی تمام شود.',
    ['پس از توقف چرخ‌دستی، پریز و قرقرهٔ پشت آن در دسترس می‌شوند.']);
  const batteryTargets=Object.keys(s.connections).filter(id=>s.connections[id]==='battery');
  const tethered=s.charging||batteryTargets.length>0;
  const tetherReason=s.charging?'کابل شارژ، رِی را به پریز بسته است.':
    'رِی با کابل کوتاه به '+batteryTargets.map(id=>NAMES[id]).join(' و ')+' وصل است؛ حتی کابل بدون برق هم حرکتش را محدود می‌کند.';
  if(s.cart<1){
    if(tethered)return hint('cart-tether','اول رِی را از کابل آزاد کن',tetherReason,
      'تا کابل رِی وصل باشد، نمی‌تواند چرخ‌دستی را عقب بکشد.',
      [unplug,'ابزار دست را بزن و روی چرخ‌دستی وسط راه بزن؛ رِی به دسته می‌رود و آن را عقب می‌کشد.']);
    return hint('cart','راه پشت چرخ‌دستی بسته است',
      'چرخ‌دستی دسترسی به ضامن کرکره و پریز پشت اتاق را بسته است.',
      'ریل زیر چرخ‌دستی را ببین؛ لازم نیست به آن برق بدهی.',
      ['ابزار دست را از نوار پایین انتخاب کن و روی چرخ‌دستی وسط راه بزن.',
       'رِی خودش کنار دسته می‌رود و آن را عقب می‌کشد؛ صبر کن حرکت تمام شود.']);
  }
  if(!s.door){
    const remainingEnergy=totalBatteryLoad(s)*Math.max(0,1-s.latchTime);
    if(powered(s,'latch')&&(s.connections.latch==='mains'||s.energy>=remainingEnergy))
      return hint('latch-powered','ضامن برق دارد؛ کمی صبر کن',
        'اتصال درست است. ضامن برای بازشدن فقط یک ثانیه برق پیوسته لازم دارد.',
        'زمان داخل راهنما متوقف است؛ آن را ببند تا ضامن آزاد شود.',
        ['کابل را فعلاً جدا نکن. بعد از بازشدن کرکره، ضامن بدون برق هم باز می‌ماند.']);
    if(s.charging)return hint(s.energy<12?'charging':'charged',
      s.energy<12?'باتری در حال شارژ است':'شارژ کافی داری؛ کابل شارژ را جدا کن',
      'هنگام شارژ، باتری نمی‌تواند هم‌زمان برق ضامن را بدهد.',
      s.energy<12?'راهنما را ببند تا حلقهٔ باتری پر شود؛ شارژ در این پنجره متوقف است.':'برای رفتن کنار کرکره، اول رِی باید از پریز آزاد شود.',
      [s.energy<12?'راهنما را ببند و بگذار باتری تا ۷۲ ژول شارژ شود.':unplug,
       s.energy<12?unplug:'ابزار کابل را بزن؛ باتری رِی و ضامن کنار کرکره را انتخاب کن.',
       ...(s.energy<12?['با ابزار کابل، باتری رِی را به ضامن کنار کرکره وصل کن.']:[])]);
    if(batteryTargets.some(id=>id!=='latch'))return hint('loads-tether','کابل وسایل، رِی را نگه داشته است',
      tetherReason,
      'چراغ و رادیو برای بازکردن در لازم نیستند؛ فعلاً انرژی و آزادی حرکتت را پس بگیر.',
      [unplug,'بعد سراغ جعبهٔ کوچک ضامن، کنار کرکره برو.']);
    const occupied=Object.keys(s.connections).find(id=>id!=='latch'&&s.connections[id]==='mains');
    if(s.energy<6||s.connections.latch==='battery'&&s.energy<remainingEnergy){
      if(s.reel&&occupied)return hint('mains-occupied','کابل بلند جای دیگری مصرف شده',
        'باتری برای بازکردن ضامن کافی نیست و تنها کابل بلند به '+NAMES[occupied]+' وصل است.',
        'برق پریز کافی است؛ کابل بلند را از وسیلهٔ قبلی به ضامن منتقل کن.',
        ['با ابزار کابل روی '+NAMES[occupied]+' بزن و «جدا کردن کابل» را بزن.',
         'با همان ابزار، پریز تعمیرگاه و ضامن کنار کرکره را انتخاب کن.']);
      if(s.reel)return hint('low-with-reel','از پریز برای بازکردن در کمک بگیر',
        'باتری برای یک ثانیه کار ضامن انرژی کافی ندارد، ولی کابل بلند همراهت است.',
        'پریز می‌تواند بدون شارژ باتری، مستقیم ضامن را باز کند.',
        ['ابزار کابل را بزن؛ پریز تعمیرگاه و سپس ضامن کنار کرکره را انتخاب کن.',
         'اتصال را یک ثانیه نگه دار تا کرکره باز شود.']);
      return hint('low-battery','انرژی ضامن را از کجا بگیریم؟',
        'ضامن ۶ وات مصرف دارد و برای یک ثانیه کار، ۶ ژول انرژی لازم دارد؛ باتری فعلی کافی نیست.',
        'پشت چرخ‌دستی هم پریز هست، هم قرقره؛ می‌توانی شارژ بگیری یا از برق مستقیم استفاده کنی.',
        [unplug,charge,'راهنما را ببند تا شارژ انجام شود؛ سپس کابل شارژ را جدا کن و باتری را به ضامن وصل کن.',
         'راه دیگر: با ابزار دست قرقره را بردار و با ابزار کابل، پریز را مستقیم به ضامن وصل کن.']);
    }
    return hint(s.reel?'latch-with-reel':'latch','جعبهٔ کنار کرکره منتظر برق است',
      'راه باز شده، ولی ضامن هنوز بسته است. روشن‌کردن چراغ و رادیو، در را باز نمی‌کند.',
      'باتری خود رِی می‌تواند ضامن را برای یک ثانیه روشن کند.',
      ['ابزار کابل را انتخاب کن؛ روی باتری رِی و سپس سوکت ضامن کنار کرکره بزن.',
       'رِی نزدیک ضامن می‌رود. یک ثانیه صبر کن تا کرکره باز شود.',
       ...(s.reel?['راه جایگزین: کابل بلند را بین پریز و ضامن وصل کن؛ اگر به وسیلهٔ دیگری وصل است، اول آن را جدا کن.']:[])]);
  }
  if(tethered)return hint('door-tether','در باز است؛ رِی هنوز به کابل بسته است',
    tetherReason+' ضامن اکنون مکانیکی باز می‌ماند و برق نمی‌خواهد.',
    'برای برداشتن رسید و عبور از در، کابل‌های باتری رِی را جدا کن.',
    [unplug,s.receipt?'ابزار دست را بزن و روی درِ خروج بزن تا رِی از آستانه رد شود.':
      'ابزار دست را بزن و رسید روی زمین کنار میز را بردار.']);
  if(!s.receipt)return hint('receipt','قبل از رفتن، سرنخ پاک‌رو را بردار',
    'کرکره باز است، اما هنوز نمی‌دانی پاک‌رو باتری را برای چه برده است.',
    'روی زمین کنار میز، یک رسید جا مانده؛ آن را با ابزار دست بردار.',
    ['ابزار دست را در نوار پایین بزن و روی «رسید پاک‌رو» کنار میز بزن.',
     'بعد روی درِ خروج بزن تا رِی از آستانهٔ کرکره عبور کند.']);
  return hint('exit','همه‌چیز برای خروج آماده است',
    'کرکره باز شده، رسید همراه توست و کابلی مانع حرکت نیست.',
    'فقط بازشدن در کافی نیست؛ رِی باید از آستانه عبور کند.',
    ['ابزار دست را انتخاب کن و روی «درِ خروج» بزن؛ بگذار رِی تا بیرون کرکره راه برود.']);
}

export class HintProgress {
  reset(){this.key=null;this.index=0;}
  constructor(){this.reset();}
  next(s){
    const advice=workshopHint(s);
    if(this.key!==advice.key){this.key=advice.key;this.index=0;}
    const messages=[advice.clue,...advice.steps];
    return messages[Math.min(this.index++,messages.length-1)];
  }
}
